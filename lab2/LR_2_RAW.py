columns = ['id', 'name', 'age']


def column_index(column):
    return columns.index(column)


def compare(a, op, b):
    if op == '=':
        return a == b
    if op == '>':
        return a > b
    if op == '<':
        return a < b
    if op == '>=':
        return a >= b
    if op == '<=':
        return a <= b
    raise ValueError(f'Неизвестный оператор: {op}')


