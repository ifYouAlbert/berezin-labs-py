class BSTNode:
    def __init__(self, key, row_id):
        self.key = key
        self.row_ids = [row_id]
        self.left = None
        self.right = None


def _bst_insert(node, key, row_id):
    if node is None:
        return BSTNode(key, row_id)

    if key < node.key:
        node.left = _bst_insert(node.left, key, row_id)
    elif key > node.key:
        node.right = _bst_insert(node.right, key, row_id)
    else:
        node.row_ids.append(row_id)

    return node


def build_bst_index(table, column):
    c = column_index(column)
    root = None

    for row_id, row in enumerate(table):
        root = _bst_insert(root, row[c], row_id)

    return root


def bst_search(table, root, op, value):
    row_ids = []

    def walk(node):
        if node is None:
            return

        if op == '=':
            if value < node.key:
                walk(node.left)
            elif value > node.key:
                walk(node.right)
            else:
                row_ids.extend(node.row_ids)
            return

        if op == '>':
            if node.key > value:
                walk(node.left)
                row_ids.extend(node.row_ids)
                walk(node.right)
            else:
                walk(node.right)
            return

        if op == '>=':
            if node.key >= value:
                walk(node.left)
                row_ids.extend(node.row_ids)
                walk(node.right)
            else:
                walk(node.right)
            return

        if op == '<':
            if node.key < value:
                walk(node.left)
                row_ids.extend(node.row_ids)
                walk(node.right)
            else:
                walk(node.left)
            return

        if op == '<=':
            if node.key <= value:
                walk(node.left)
                row_ids.extend(node.row_ids)
                walk(node.right)
            else:
                walk(node.left)
            return

        raise ValueError(f'Неизвестный оператор: {op}')

    walk(root)
    row_ids.sort()
    return [table[row_id] for row_id in row_ids]


